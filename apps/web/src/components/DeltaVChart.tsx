import { formatSpeed, type Evaluation } from '@rocket-odyssey/game-core';
import { cx } from '../lib/cx.ts';
import { AlertIcon, CheckIcon } from './icons.tsx';

/**
 * Colours of the two stages: the first two slots of a categorical palette,
 * checked against the panel surface for colour-blind separation and 3:1
 * contrast. The stages are also named in the legend and labelled with their
 * amounts, so they are never told apart by colour alone.
 */
const STAGE_COLORS = ['#3987e5', '#d95926'] as const;

interface DeltaVChartProps {
  deltaV: Evaluation['deltaV'];
  orbitName: string;
}

/**
 * The delta-v the rocket generated, split by stage, against what the orbit
 * needs: one bar measured against a limit. Every number in the bar is also
 * given as text below it.
 */
export function DeltaVChart({ deltaV, orbitName }: DeltaVChartProps) {
  const stages = deltaV.budget.stages;
  const total = deltaV.budget.totalMs;
  const required = deltaV.requiredMs;
  // A little room on the right so the marker of the limit is never cut off.
  const domain = Math.max(total, required) * 1.04;
  const share = (value: number) => `${(value / domain) * 100}%`;
  const requiredShare = (required / domain) * 100;
  const enough = deltaV.marginMs >= 0;

  return (
    <figure>
      <figcaption className="label !text-line-bright">
        Delta-v: generated against required
      </figcaption>

      <div className="relative mt-9 h-7" aria-hidden="true">
        <div className="flex h-full gap-0.5">
          {stages.map((stage, index) => (
            <div
              key={stage.name}
              title={`${stage.name}: ${formatSpeed(stage.deltaVMs)}`}
              // In forced colours the stages keep their own colours, which the legend names.
              className="grid h-full min-w-0 place-items-center overflow-hidden rounded-[4px] px-1 forced-colors:forced-color-adjust-none"
              style={{ width: share(stage.deltaVMs), backgroundColor: STAGE_COLORS[index] }}
            >
              {stage.deltaVMs / domain > 0.16 && (
                // Dark on both stage colours: 5.6:1 and 5.2:1. White was 3.6:1 and 3.9:1.
                <span className="readout truncate text-sm font-bold text-space-950">
                  {formatSpeed(stage.deltaVMs)}
                </span>
              )}
            </div>
          ))}
        </div>
        {/* The limit: what the orbit needs. */}
        <div
          className="absolute -bottom-1.5 -top-1.5 w-0.5 bg-ink forced-colors:bg-[CanvasText]"
          style={{ left: `${requiredShare}%` }}
        />
        <p
          className={cx(
            'absolute -top-8 whitespace-nowrap text-sm font-semibold text-ink',
            requiredShare > 78 ? '-translate-x-full pr-1.5' : 'pl-1.5',
          )}
          style={{ left: `${requiredShare}%` }}
        >
          Required: {formatSpeed(required)}
        </p>
      </div>

      <ul className="mt-3 flex flex-wrap gap-x-6 gap-y-1">
        {stages.map((stage, index) => (
          <li key={stage.name} className="flex items-center gap-2">
            <span
              aria-hidden="true"
              className="size-3.5 flex-none rounded-[3px]"
              style={{ backgroundColor: STAGE_COLORS[index] }}
            />
            <span className="text-ink-soft">{stage.name}:</span>
            <span className="font-bold text-ink tabular-nums">{formatSpeed(stage.deltaVMs)}</span>
          </li>
        ))}
      </ul>

      <dl className="mt-2 grid grid-cols-[auto_1fr] gap-x-4 gap-y-0.5">
        <dt className="text-ink-soft">Generated by the rocket:</dt>
        <dd className="font-bold text-ink tabular-nums">{formatSpeed(total)}</dd>
        <dt className="text-ink-soft">Required by {orbitName}:</dt>
        <dd className="font-bold text-ink tabular-nums">{formatSpeed(required)}</dd>
        <dt className="text-ink-soft">{enough ? 'Reserve:' : 'Shortfall:'}</dt>
        <dd
          className={cx(
            'flex items-center gap-1.5 font-bold tabular-nums',
            enough ? 'text-go' : 'text-stop',
          )}
        >
          {enough ? <CheckIcon /> : <AlertIcon />}
          {formatSpeed(Math.abs(deltaV.marginMs))} {enough ? 'to spare' : 'short'}
        </dd>
      </dl>
    </figure>
  );
}
